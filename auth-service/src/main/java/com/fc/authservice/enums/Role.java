package com.fc.authservice.enums;

/**
 * Enumeration representing different roles available in the system.
 * Roles determine the level of access and permissions granted to a user.
 * USER  - Standard user with access to general application features.
 * ADMIN - Administrator with elevated privileges for managing users and content.
 * Additional roles can be added here as the system grows.
 *
 * @author Romy Rose Jimmy
 * @since 2025
 */
public enum Role {
    USER,
    ADMIN
}
